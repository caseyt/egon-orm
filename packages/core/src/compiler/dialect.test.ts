test("the lock clauses the query builder writes: four modes, each alone, with SKIP LOCKED or NOWAIT", () => {
  expect(LOCK_CLAUSES).toStrictEqual(Object.keys(POSTGRES_LOCK_SQL));
  expect(Object.isFrozen(LOCK_CLAUSES)).toBe(true);
});

describe.each([postgresDialect, mysqlDialect, sqliteDialect])("$name", (dialect) => {
  test("every entry of the table", () => {
    expect(dialect).toStrictEqual(EXPECTED_DIALECTS[dialect.name]);
  });

  test("the table and the tables inside it are frozen", () => {
    expect(Object.isFrozen(dialect)).toBe(true);
    for (const value of Object.values(dialect)) {
      if (typeof value === "object" && value !== null) expect(Object.isFrozen(value)).toBe(true);
    }
    expect(Object.isFrozen(dialect.capabilities.lockModes)).toBe(true);
    expect(Object.isFrozen(dialect.capabilities.isolationLevels)).toBe(true);
  });

  test("its lock modes are the keys of its lock table", () => {
    expect(dialect.capabilities.lockModes).toStrictEqual(Object.keys(dialect.locks));
  });
});

test("the exported capability objects are the ones in the dialect tables", () => {
  expect(postgresDialect.capabilities).toBe(POSTGRES_CAPABILITIES);
  expect(mysqlDialect.capabilities).toBe(MYSQL_CAPABILITIES);
  expect(sqliteDialect.capabilities).toBe(SQLITE_CAPABILITIES);
});
