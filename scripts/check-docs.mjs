// Checks of the documentation site (docs/site) that VitePress itself does not make. Run by
// `pnpm lint` (as `pnpm docs:check`); VitePress's own build fails on dead links.
//
// 1. No hand-written code block in TypeScript or JavaScript, in the site, the README or
//    CONTRIBUTING: every such block is a region of a checked file, included with
//    `<<< @/examples/file.ts#region` (the README's copy of one is check 7's). A block that is
//    deliberately wrong code may stay inline with `<!-- illustrative -->` on the line above.
//    Shell, SQL, text and config blocks are allowed.
// 2. Every snippet include names a file that exists and, when it names a region, a region
//    that the file opens and closes.
// 3. A `// =>` comment, which states the value of a statement, appears only in an example
//    marked `// @run`, whose comments CI checks (project docs:integration).
// 4. No page, example, README or source comment names the design reference that plan
//    README §8 keeps out of everything users read (FORBIDDEN_NAME below).
// 5. Every export of every public entry point is listed in the index of exports
//    (reference/exports.md, generated by scripts/api-index.ts), and every export that is a
//    value (a function, class or constant) also appears as code (in backticks, a code block
//    or an included example) on a written page of the guide, recipes, reference or internals.
// 6. Every page is in the sidebar, and every sidebar link is a page.
// 7. The README's example is the `example` region of docs/site/examples/home.ts.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = join(ROOT, "docs/site");

/** Languages whose fenced blocks must come from checked files. */
const CHECKED_LANGUAGES = new Set([
  "ts",
  "typescript",
  "tsx",
  "js",
  "javascript",
  "jsx",
  "mjs",
  "cjs",
  "mts",
  "cts",
]);
const ILLUSTRATIVE = "<!-- illustrative -->";

/** The public entry points and the specifier users import them by. */
export const ENTRY_POINTS = {
  "egon-orm": "packages/core/src/index.ts",
  "egon-orm/testing": "packages/core/src/testing.ts",
  "egon-orm/migration": "packages/core/src/migration/index.ts",
  "@egon-orm/postgres": "packages/postgres/src/index.ts",
  "@egon-orm/sqlite": "packages/sqlite/src/index.ts",
  "@egon-orm/mysql": "packages/mysql/src/index.ts",
  "@egon-orm/zod": "packages/zod/src/index.ts",
  "@egon-orm/cli": "packages/cli/src/index.ts",
};

/** Files under `dir` (recursively) whose name passes `keep`, skipping `node_modules` and build output. */
export function walk(dir, keep) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", "dist", ".tsbuild", "cache", "coverage"].includes(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(path, keep));
    else if (keep(entry.name)) out.push(path);
  }
  return out;
}

/** The fenced code blocks of a Markdown text: language, opening line (1-based), and the line before. */
export function fencedBlocks(markdown) {
  const lines = markdown.split("\n");
  const blocks = [];
  let open;
  for (let i = 0; i < lines.length; i++) {
    const match = /^\s*(`{3,}|~{3,})\s*([\w-]*)/.exec(lines[i]);
    if (match === null) continue;
    if (open === undefined) {
      let before = i - 1;
      while (before >= 0 && lines[before].trim() === "") before--;
      open = {
        fence: match[1],
        language: match[2].toLowerCase(),
        line: i + 1,
        previous: lines[before]?.trim() ?? "",
      };
    } else if (match[1][0] === open.fence[0] && match[1].length >= open.fence.length && match[2] === "") {
      blocks.push(open);
      open = undefined;
    }
  }
  return blocks;
}

/**
 * Problems with hand-written blocks in one page. In the README, a block right after
 * `<!-- example: … -->` is allowed: check 7 compares it with the checked region it copies.
 */
export function handWrittenBlocks(markdown, { readme = false } = {}) {
  return fencedBlocks(markdown)
    .filter((block) => CHECKED_LANGUAGES.has(block.language) && block.previous !== ILLUSTRATIVE)
    .filter((block) => !(readme && /^<!-- example: \S+#[\w-]+ -->$/.test(block.previous)))
    .map(
      (block) =>
        `line ${block.line}: a hand-written \`${block.language}\` block. Include it from a checked file under docs/site/examples (<<< @/examples/file.ts#region), or mark deliberately invalid code with ${ILLUSTRATIVE} on the line above.`,
    );
}

/** The snippet includes of a page: `<<< path#region`, with the path as written. */
export function snippetIncludes(markdown) {
  const includes = [];
  markdown.split("\n").forEach((line, index) => {
    const match = /^\s*<<<\s+(\S+?)(?:#([\w-]+))?(?:\{[^}]*\})?\s*$/.exec(line);
    if (match !== null) includes.push({ path: match[1], region: match[2], line: index + 1 });
  });
  return includes;
}

/** Whether `source` opens and closes the region `name` (`// #region name` … `// #endregion name`). */
export function hasRegion(source, name) {
  const escaped = name.replace(/[-]/g, "\\-");
  return (
    new RegExp(`(?://|<!--|/\\*)\\s*#region ${escaped}(?![\\w-])`).test(source) &&
    new RegExp(`(?://|<!--|/\\*)\\s*#endregion ${escaped}(?![\\w-])`).test(source)
  );
}

/** The name plan README §8 keeps out of pages, TSDoc and comments, as a whole word. */
const FORBIDDEN_NAME = /\becto\b/i;

/** Lines of a text that use the forbidden name. */
export function forbiddenNameMentions(text) {
  return text
    .split("\n")
    .map((line, index) => ({ line, index }))
    .filter(({ line }) => FORBIDDEN_NAME.test(line))
    .map(({ index }) => index + 1);
}

/** `// =>` comments in a file that is not marked `// @run`. */
export function uncheckedValueComments(source) {
  if (/^\/\/ @run\b/m.test(source.slice(0, 2000))) return [];
  return source
    .split("\n")
    .map((line, index) => ({ line, index }))
    .filter(({ line }) => /\/\/ => /.test(line))
    .map(({ index }) => index + 1);
}

/**
 * The names a module exports, read from its `export` statements, each with whether it is a
 * type only (`export type { … }`, `export { type … }`, an interface or a type alias).
 */
export function exportedNames(source) {
  const names = new Map();
  for (const match of source.matchAll(/export\s+(type\s+)?\{([^}]*)\}/g)) {
    for (const part of match[2].split(",")) {
      const trimmed = part.trim();
      const name = trimmed
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/)
        .pop()
        ?.trim();
      if (name) names.set(name, match[1] !== undefined || trimmed.startsWith("type "));
    }
  }
  for (const match of source.matchAll(
    /export\s+(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(const|let|function\*?|class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/g,
  )) {
    names.set(match[2], match[1] === "interface" || match[1] === "type");
  }
  return [...names]
    .map(([name, typeOnly]) => ({ name, typeOnly }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * The code of a Markdown text: its inline code spans and fenced blocks, without the prose. A
 * name counts as shown on a page only there (or in an included example), so that an export
 * called `from` or `count` is not "found" in an English sentence.
 */
export function codeOf(markdown) {
  const fences = [...markdown.matchAll(/^\s*(`{3,}|~{3,})[^\n]*\n([\s\S]*?)^\s*\1\s*$/gm)].map((m) => m[2]);
  const prose = markdown.replace(/^\s*(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\s*\1\s*$/gm, "");
  const spans = [...prose.matchAll(/(`+)([\s\S]+?)\1/g)].map((m) => m[2]);
  return [...fences, ...spans].join("\n");
}

/** The code of a region of a source file, without its markers. */
export function regionText(source, name) {
  const lines = source.split("\n");
  const start = lines.findIndex((line) => line.trim() === `// #region ${name}`);
  const end = lines.findIndex((line) => line.trim() === `// #endregion ${name}`);
  if (start === -1 || end <= start) return undefined;
  return lines.slice(start + 1, end).join("\n");
}

function main() {
  const problems = [];
  const report = (file, message) => problems.push(`${relative(ROOT, file)}: ${message}`);

  const pages = walk(SITE, (name) => name.endsWith(".md")).filter(
    (file) => !relative(SITE, file).startsWith("api/reference/"),
  );

  // 1, also over the README and CONTRIBUTING, which GitHub shows
  for (const file of [join(ROOT, "README.md"), join(ROOT, "CONTRIBUTING.md")]) {
    const readme = file.endsWith("README.md");
    for (const message of handWrittenBlocks(readFileSync(file, "utf8"), { readme })) report(file, message);
  }

  // 1, 2
  for (const page of pages) {
    const markdown = readFileSync(page, "utf8");
    for (const message of handWrittenBlocks(markdown)) report(page, message);
    for (const include of snippetIncludes(markdown)) {
      const file = include.path.startsWith("@/")
        ? join(SITE, include.path.slice(2))
        : resolve(dirname(page), include.path);
      if (!existsSync(file)) {
        report(page, `line ${include.line}: the included file ${include.path} does not exist.`);
      } else if (include.region !== undefined && !hasRegion(readFileSync(file, "utf8"), include.region)) {
        report(page, `line ${include.line}: ${include.path} has no region "${include.region}".`);
      }
    }
  }

  // 3
  const examples = [
    ...walk(join(SITE, "examples"), (name) => /\.(ts|tsx)$/.test(name)),
    ...walk(join(ROOT, "examples"), (name) => /\.(ts|tsx)$/.test(name)),
  ];
  for (const file of examples) {
    for (const line of uncheckedValueComments(readFileSync(file, "utf8"))) {
      report(
        file,
        `line ${line}: a // => comment in a file that is not marked // @run, so nothing checks it. Mark the file // @run, or write the value as a plain // comment.`,
      );
    }
  }

  // 4
  const positioningScope = [
    ...pages,
    ...examples,
    join(ROOT, "README.md"),
    join(ROOT, "CONTRIBUTING.md"),
    ...walk(join(ROOT, "packages"), (name) => /\.(ts|tsx|mjs|md)$/.test(name)),
  ];
  for (const file of positioningScope) {
    for (const line of forbiddenNameMentions(readFileSync(file, "utf8"))) {
      report(
        file,
        `line ${line}: names the design reference that plan README §8 keeps out. Pages, examples and comments present the library on its own terms.`,
      );
    }
  }

  // 5
  const index = readFileSync(join(SITE, "reference/exports.md"), "utf8");
  const handWritten = pages
    .filter((file) => /^(guide|recipes|reference|internals)\//.test(relative(SITE, file)))
    .filter((file) => !file.endsWith("reference/exports.md"))
    .flatMap((page) => {
      const markdown = readFileSync(page, "utf8");
      const included = snippetIncludes(markdown).map((include) => {
        const file = include.path.startsWith("@/")
          ? join(SITE, include.path.slice(2))
          : resolve(dirname(page), include.path);
        if (!existsSync(file)) return "";
        const source = readFileSync(file, "utf8");
        return include.region === undefined ? source : (regionText(source, include.region) ?? "");
      });
      return [codeOf(markdown), ...included];
    })
    .join("\n");
  for (const [specifier, entry] of Object.entries(ENTRY_POINTS)) {
    for (const { name, typeOnly } of exportedNames(readFileSync(join(ROOT, entry), "utf8"))) {
      const word = new RegExp(`\\b${name.replace(/\$/g, "\\$")}\\b`);
      if (!index.includes(`[\`${name}\`]`)) {
        report(
          join(ROOT, entry),
          `${specifier} exports ${name}, which reference/exports.md does not list: run pnpm docs:exports.`,
        );
      } else if (!typeOnly && !word.test(handWritten)) {
        report(
          join(ROOT, entry),
          `${specifier} exports ${name}, which no page of the guide, recipes, reference or internals shows as code (in backticks, a code block or an included example).`,
        );
      }
    }
  }

  // 6
  const config = readFileSync(join(SITE, ".vitepress/config.ts"), "utf8");
  // Links only: a sidebar key ("/guide/": …) is followed by a colon.
  const linked = new Set(
    [...config.matchAll(/"(\/(?:guide|recipes|reference|internals|api)\/[\w-]*)"(?!\s*:)/g)].map((m) => m[1]),
  );
  for (const link of linked) {
    const file = link.endsWith("/") ? join(SITE, link, "index.md") : join(SITE, `${link}.md`);
    if (!existsSync(file))
      report(join(SITE, ".vitepress/config.ts"), `the sidebar links to ${link}, which is not a page.`);
  }
  for (const page of pages) {
    const path = relative(SITE, page).replace(/\.md$/, "");
    if (path === "index") continue;
    const link =
      path.endsWith("/index") || path === "index" ? `/${path.slice(0, -"index".length)}` : `/${path}`;
    if (!linked.has(link)) report(page, `the page is not in the sidebar (${link}).`);
  }

  // 7
  const readme = readFileSync(join(ROOT, "README.md"), "utf8");
  const example = regionText(readFileSync(join(SITE, "examples/home.ts"), "utf8"), "example");
  const block = /<!-- example: docs\/site\/examples\/home\.ts#example -->\s*```ts\n([\s\S]*?)\n```/.exec(
    readme,
  )?.[1];
  if (example === undefined) report(join(SITE, "examples/home.ts"), "has no region example.");
  else if (block !== example) {
    report(
      join(ROOT, "README.md"),
      "the example after <!-- example: docs/site/examples/home.ts#example --> must be that region, as it is (copy it again).",
    );
  }

  if (problems.length > 0) {
    process.stderr.write(
      `check-docs: ${problems.length} problem(s)\n${problems.map((p) => `  ${p}`).join("\n")}\n`,
    );
    process.exitCode = 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
